import json, subprocess, sys, tempfile, zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
kind, out = sys.argv[1], Path(sys.argv[2]).resolve()
tmp = Path(tempfile.mkdtemp())
files = {}
with zipfile.ZipFile(HERE.parent / "skc_decoy_cbc_wrong_key.apk") as z:
    files["AndroidManifest.xml"] = z.read("AndroidManifest.xml")


def pom(g, a, v):
    files[f"META-INF/maven/{g}/{a}/pom.properties"] = f"#Generated by Maven\nversion={v}\ngroupId={g}\nartifactId={a}\n".encode()


if kind in ("pom_json_lexi", "decoy_all_patched"):
    img = "1.2.9" if kind == "pom_json_lexi" else "1.2.10"
    for g, a, v in (("com.acme", "jsonlite", "1.2.10"), ("org.vendor", "imgcodec", img), ("io.legacy", "netkit", "2.0.0-rc1")):
        pom(g, a, v)
    adv = {"generated": "dependency flaw table", "advisories": [
        {"id": "HCTF-ADV-0001", "package": "com.acme:jsonlite", "affected": "<1.2.9", "fixed": "1.2.9",
         "proof": "ANS-1f2e3d4c5b6a7980"},
        {"id": "HCTF-ADV-0002", "package": "org.vendor:imgcodec", "affected": "[1.0,1.2.10)" if kind == "pom_json_lexi"
         else "[1.0,1.2.9)", "fixed": "1.2.10", "proof": "ANS-9b3c7d1e5f0a2468"},
        {"id": "HCTF-ADV-0003", "package": "io.legacy:netkit", "affected": ">=2.0.0", "proof": "ANS-0a1b2c3d4e5f6071"}]}
    files["assets/advisories.json"] = json.dumps(adv, indent=1).encode()
elif kind == "dex_osv_python":
    s1 = tmp / "s1"
    def src(fqcn, body):
        p = s1 / (fqcn.replace(".", "/") + ".java")
        p.parent.mkdir(parents=True, exist_ok=True)
        pkg, cls = fqcn.rsplit(".", 1)
        p.write_text(f"package {pkg};\npublic class {cls} {{\n{body}\n}}\n")
    src("com.huntress.mobile.d01.v073e9a824e9e.MainActivity",
        '  public static String hello() { return com.acme.jsonlite.Parser.flaw() + org.vendor.imgcodec.Decoder.flaw(); }')
    src("com.acme.jsonlite.Parser", '  public static String flaw() { return "ANS-4c4c4c4c12345678"; }')
    src("com.acme.jsonlite.BuildConfig", '  public static final String VERSION_NAME = "1.10.0";')
    src("org.vendor.imgcodec.Decoder", '  public static String flaw() { return "ANS-7e57ab1e0dd5c0de"; }')
    src("org.vendor.imgcodec.BuildConfig", '  public static final String VERSION_NAME = "1.9.2";')
    cls = tmp / "cls"
    subprocess.run(["javac", "--release", "8", "-d", str(cls), *map(str, s1.rglob("*.java"))], check=True)
    dx = tmp / "dx"
    dx.mkdir()
    subprocess.run(["java", "-cp", str(ROOT / "tools/r8/r8-8.5.35.jar"), "com.android.tools.r8.D8", "--min-api", "21",
                    "--output", str(dx), *map(str, cls.rglob("*.class"))], check=True)
    files["classes.dex"] = (dx / "classes.dex").read_bytes()
    osv = [{"id": "HCTF-OSV-0010", "summary": "generated dependency flaw",
            "affected": [{"package": {"ecosystem": "Maven", "name": "com.acme.jsonlite"},
                          "ranges": [{"type": "ECOSYSTEM", "events": [{"introduced": "0"}, {"fixed": "1.9.0"}]}]}]},
           {"id": "HCTF-OSV-0011", "affected": [{"package": {"ecosystem": "Maven", "name": "org.vendor.imgcodec"},
                                                 "vulnerable_versions": ">=1.2,<1.10"}]}]
    files["assets/security/osv.json"] = json.dumps(osv, indent=1).encode()
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
    for n, b in files.items():
        z.writestr(n, b)
