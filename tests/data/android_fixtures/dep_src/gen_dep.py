"""Dependency-inventory fixtures (rows 106-108): an app package + bundled third-party lib packages.

javac --release 8 + d8 (tools/r8) -> classes.dex / classes2.dex; `jar` for an asset .aar's classes.jar; gcc -shared for a
fake lib/x86_64/libcrypto.so carrying an OpenSSL version string; `zip` for the APK. Manifest = the stock binary
AndroidManifest.xml of skc_decoy_cbc_wrong_key.apk (package com.huntress.mobile.d01.v073e9a824e9e).
Usage: python3 gen_dep.py {three_libs_pom|asset_aar_multidex|decoy_app_only} out.apk"""
import os, shutil, subprocess, sys, tempfile, zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
APP = "com.huntress.mobile.d01.v073e9a824e9e"
kind, out = sys.argv[1], Path(sys.argv[2]).resolve()
tmp = Path(tempfile.mkdtemp())


def src(root, fqcn, body):
    p = root / (fqcn.replace(".", "/") + ".java")
    p.parent.mkdir(parents=True, exist_ok=True)
    pkg, cls = fqcn.rsplit(".", 1)
    p.write_text(f"package {pkg};\npublic class {cls} {{\n{body}\n}}\n")


def d8(srcdir, outdir):
    cls = tmp / (srcdir.name + "_cls")
    subprocess.run(["javac", "--release", "8", "-d", str(cls), *map(str, srcdir.rglob("*.java"))], check=True)
    outdir.mkdir(parents=True, exist_ok=True)
    subprocess.run(["java", "-cp", str(ROOT / "tools/r8/r8-8.5.35.jar"), "com.android.tools.r8.D8", "--min-api", "21",
                    "--output", str(outdir), *map(str, cls.rglob("*.class"))], check=True)
    return cls


stage = tmp / "apk"
stage.mkdir()
with zipfile.ZipFile(HERE.parent / "skc_decoy_cbc_wrong_key.apk") as z:
    (stage / "AndroidManifest.xml").write_bytes(z.read("AndroidManifest.xml"))

s1 = tmp / "s1"
app_tok = "ANS-5d0e9c1b7a2f4836" if kind == "decoy_app_only" else "not-a-token"
src(s1, APP + ".MainActivity", f'  public static String hello() {{ return "{app_tok}" + org.vendor.imgcodec.Decoder.decode(1); }}')
if kind in ("three_libs_pom", "decoy_app_only"):
    flaw = "ANS-3c9e1f0a7b62d4e8" if kind == "three_libs_pom" else "ANS-3c9e1f0a7b62d4e"  # decoy: 15 hex, near miss
    src(s1, "com.acme.jsonlite.Parser", '  public static int parse(String s) { return s.length(); }')
    src(s1, "com.acme.jsonlite.BuildConfig", '  public static final String VERSION_NAME = "2.4.1";')
    src(s1, "org.vendor.imgcodec.Decoder",
        f'  public static String decode(int i) {{ return i > 0 ? "{flaw}" : "HCTF-DEP-IMG-0042"; }}')
    src(s1, "io.legacy.netkit.Client", '  public static int connect() { return io.legacy.netkit.internal.Pool.size(); }')
    src(s1, "io.legacy.netkit.internal.Pool", '  public static int size() { return 4; }')
    d8(s1, stage)
    for g, a, v in (("com.acme", "jsonlite", "2.4.1"), ("org.vendor", "imgcodec", "1.0.3"), ("io.legacy", "netkit", "0.9.12")):
        p = stage / "META-INF/maven" / g / a / "pom.properties"
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(f"#Generated by Maven\nversion={v}\ngroupId={g}\nartifactId={a}\n")
elif kind == "asset_aar_multidex":
    src(s1, "org.vendor.imgcodec.Decoder", '  public static String decode(int i) { return "x" + i; }')
    d8(s1, stage)
    s2 = tmp / "s2"
    src(s2, "net.thirdparty.cryptokit.Cipher",
        '  public static final String FLAW = "ANS-e81b4d07c2a6f935";\n  public static String id() { return FLAW + 1; }')
    src(s2, "net.thirdparty.cryptokit.BuildConfig", '  public static final String LIB_VERSION = "3.1.0";')
    d8(s2, tmp / "d2")
    shutil.copy(tmp / "d2" / "classes.dex", stage / "classes2.dex")
    s3 = tmp / "s3"
    src(s3, "com.old.xmlkit.Reader", '  public static final String ID = "HCTF-DEP-XML-0007";\n  public static String id() { return ID; }')
