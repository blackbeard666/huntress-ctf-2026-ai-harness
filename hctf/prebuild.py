def _load_json(p, default):
    try:
        return json.loads(Path(p).read_text())
    except (OSError, ValueError):
        return default


def atlas_gaps(cfg):
    """`action: prebuild` readiness gaps of the lane's coverage atlas (reference/coverage/<lane>.md, ```json block under
    "## Readiness gaps"), as targets {id, goal, priority, source}. [] when the atlas is missing / unparsable."""
    p = ROOT / cfg["atlas"] if cfg.get("atlas") else None
    if not p or not p.exists():
        return []
    m = re.search(r"## Readiness gaps.*?```json\s*(.*?)```", p.read_text(errors="replace"), re.S)
    try:
        gaps = json.loads(m.group(1)) if m else []
    except ValueError:
        return []
    return [{"id": g["id"], "goal": f"{g.get('concept', g['id'])}: {g.get('detail', '')}".strip(": "),
             "priority": int(g.get("priority") or 3), "source": f"coverage atlas {cfg['atlas']}"}
            for g in gaps if isinstance(g, dict) and g.get("id") and g.get("action") == "prebuild"]


def targets(cfg):
    """Ranked: atlas priority-1 gaps, then the lane's TARGETS.json (hand-ranked), then atlas priority 2, 3. A TARGETS
    entry the atlas also names keeps its own fields but takes the atlas rank."""
    t = _load_json(ROOT / cfg["targets"], {}) if cfg.get("targets") else {}
    base = list(t.get("targets", t) if isinstance(t, dict) else t)
    gaps = atlas_gaps(cfg)
    prio = {g["id"]: g["priority"] for g in gaps}
    by_id = {x.get("id"): x for x in base}
    out, seen = [], set()

    def add(x):
        if x.get("id") and x["id"] not in seen:
            seen.add(x["id"])
            out.append(by_id.get(x["id"], x))
    for g in gaps:
        if g["priority"] <= 1:
            add(g)
    for x in base:
        if prio.get(x.get("id"), 2) >= 2:
            add(x)
    for g in sorted(gaps, key=lambda g: g["priority"]):
        add(g)
    return out


def registered_fields():
    """{(fmt, field)} lib.meta can answer, read in a FRESH interpreter (this process may hold a stale import)."""
    r = subprocess.run([sys.executable, "-c", "import json, lib.meta as m; print(json.dumps(sorted(m.REGISTRY)))"],
                       cwd=ROOT, capture_output=True, text=True, timeout=60,
                       env=dict(os.environ, PYTHONPATH=str(ROOT), HCTF_META_MAX_DAY="0"))
    try:
        return {tuple(k) for k in json.loads(r.stdout.strip().splitlines()[-1])}
    except (IndexError, ValueError):
        return set()


def _target_done(lane, t, reg):
    if lane == "metadata-forensics" and t.get("fmt") and t.get("fields"):
        return all((t["fmt"], f) in reg for f in t["fields"])
    return False


def pending(lane, cfg, n, only=None):
    """The next `n` targets: ranked order, minus done ones and ones that failed MAX_ATTEMPTS times."""
    state = _load_json(STATE, {})
    reg = registered_fields() if lane == "metadata-forensics" else set()
    out = []
    for t in targets(cfg):
        tid = t.get("id")
        if not tid or (only and tid not in only):
            continue
        st = state.get(f"{lane}:{tid}", {})
        if st.get("ok") or _target_done(lane, t, reg) or (not only and st.get("attempts", 0) >= MAX_ATTEMPTS):
            continue
        out.append(t)
    for tid in only or ():
        if not any(t.get("id") == tid for t in out) and not any(t.get("id") == tid for t in targets(cfg)):
            out.append({"id": tid, "goal": tid})       # ad-hoc target named on the command line
    return out[:n] if n else out


def _record(lane, tid, **kw):
    state = _load_json(STATE, {})
    st = state.setdefault(f"{lane}:{tid}", {"attempts": 0})
    st["attempts"] = st.get("attempts", 0) + 1
    st.update(kw, last=time.strftime("%Y-%m-%dT%H:%M:%S"))
    STATE.write_text(json.dumps(state, indent=1, sort_keys=True))


