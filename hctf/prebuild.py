def history_costs():
    return [float(r["cost_usd"]) for r in workers.read_metrics()
            if r.get("stage") == "prebuild" and isinstance(r.get("cost_usd"), (int, float)) and r["cost_usd"] > 0]


def budget_for(n):
    """Batch budget: n x the p75 historical prebuild worker cost (DEFAULT_COST before any history), capped."""
    h = sorted(history_costs())
    per = h[min(len(h) - 1, int(len(h) * 0.75))] if h else DEFAULT_COST
    return round(min(BUDGET_CAP, max(per, 0.5) * max(n, 1) * 1.2), 2)


def next_drop(now=None, drop=None):
    now = now or datetime.now()
    hh, mm = (int(x) for x in (drop or DROP_LOCAL).split(":"))
    d = now.replace(hour=hh, minute=mm, second=0, microsecond=0)
    return d if d > now else d + timedelta(days=1)


def default_deadline(now=None):
    """DEADLINE_MARGIN_MIN before the next daily drop (host local time)."""
    return next_drop(now) - timedelta(minutes=DEADLINE_MARGIN_MIN)


def parse_deadline(hhmm, now=None):
    now = now or datetime.now()
    hh, mm = (int(x) for x in hhmm.split(":"))
    d = now.replace(hour=hh, minute=mm, second=0, microsecond=0)
    return d if d > now else d + timedelta(days=1)


