def gate(lane, cfg, snap_root, before_dirty, before_src, base_regress=None, log=print, info=None):
    """(ok, [reasons]). Never raises. `info` (dict) receives "after": the post-merge regress baseline (the next
    target's baseline when this one is kept -- no second full replay)."""
    reasons = []
    try:
        changed = changed_paths(snap_root, cfg)
        if not changed:
            return False, ["no change (nothing written)"]
        outside = [p for p in changed if not _in(p, cfg["writable"])]
        outside += sorted(p for p in _git_dirty() - before_dirty
                          if not _in(p, cfg["writable"]) and not _in(p, cfg["snapshot"]))
        if outside:
            reasons.append("wrote outside the allowlist: " + ", ".join(outside[:8]))
        for p in changed:
            # in-window code only: an offline fixture GENERATOR under tests/data/ may use random/subprocess/open (D15
            # night: binary aes-tea-chacha-hcfg reverted for its cipher_gen.py, not for its lib/binary.py change)
            if p.endswith(".py") and p.startswith("lib/") and (ROOT / p).exists():
                reasons += ast_problems(ROOT / p, before_src.get(p))
        if "meta" in cfg.get("checks", ()):
            reasons += meta_structure_problems() + _fresh_fixture_problems()
        if reasons:
            return False, reasons
        # the lane's suites in parallel subprocesses, the solver-case regress replay beside them (one lane holds the lock)
        procs = {t: subprocess.Popen([sys.executable, t], cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                     text=True, env=dict(os.environ, HCTF_META_MAX_DAY="0"))
                 for t in gate_suites(lane, cfg)}
        reg = {}
        thr = None
        if cfg.get("regress_lane") and base_regress is not None:
            def _reg():
                try:
                    reg["after"] = regress_baseline(cfg["regress_lane"])
                except Exception as e:  # noqa: BLE001
                    reg["error"] = repr(e)
            thr = threading.Thread(target=_reg, daemon=True)
            thr.start()
        end = time.time() + 900
        for t, p in procs.items():
            try:
                outp, _ = p.communicate(timeout=max(1.0, end - time.time()))
                if p.returncode:
                    tail = (outp or "").strip().splitlines()[-3:]
                    reasons.append(f"{t} fails: {' | '.join(tail)[:400]}")
            except subprocess.TimeoutExpired:
                p.kill()
                p.communicate()
                reasons.append(f"{t} timed out")
        if thr is not None:
            thr.join()
            if "error" in reg:
                reasons.append(f"regress replay error {reg['error']}")
            else:
                after = reg["after"]
                if info is not None:
                    info["after"] = after
                broke = [k for k, ok in base_regress.items() if ok and not after.get(k)]
                if broke:
                    reasons.append(f"{len(broke)} verified {cfg['regress_lane']} case(s) regress: {broke[:4]}")
    except Exception as e:  # noqa: BLE001 - a crashing gate is a failing gate
        reasons.append(f"gate error {e!r}")
    return not reasons, reasons


# ------------------------------------------------------------------------------------------------ snapshot
def snapshot(cfg):
    shutil.rmtree(SNAP, ignore_errors=True)
    SNAP.mkdir(parents=True)
    for d in cfg["snapshot"]:
        if (ROOT / d).exists():
            shutil.copytree(ROOT / d, SNAP / d, ignore=shutil.ignore_patterns("__pycache__"))
    (SNAP / "snapshot.json").write_text(json.dumps({"dirs": list(cfg["snapshot"]), "dirty": sorted(_git_dirty()),
                                                    "t": time.time()}))
    return SNAP


def _sync_dir(src, dst):
    """Make dst's tree equal src's IN PLACE -- never remove dst itself. A parallel lane worker's bwrap bind sits ON
    ROOT/lib and ROOT/tests/data: deleting that directory detaches the bind in every worker namespace (Linux >= 3.18),
    and those workers then write straight into the real tree (2026-10-16: 36 ungated files leaked into main)."""
    src, dst = Path(src), Path(dst)
    dst.mkdir(parents=True, exist_ok=True)
    for q in sorted(dst.rglob("*"), key=lambda x: len(x.parts), reverse=True):
        rel = q.relative_to(dst)
        if "__pycache__" in rel.parts:
            continue
        p = src / rel
        if not p.exists() or p.is_dir() != q.is_dir():
            if q.is_dir() and not q.is_symlink():
                shutil.rmtree(q, ignore_errors=True)
            else:
                q.unlink(missing_ok=True)
    for p in sorted(src.rglob("*")):
        rel = p.relative_to(src)
        if "__pycache__" in rel.parts:
            continue
        q = dst / rel
        if p.is_dir():
            q.mkdir(parents=True, exist_ok=True)
        elif not q.exists() or not filecmp.cmp(p, q, shallow=False):
            q.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, q)


def restore(log=print, reason=""):
    """Put lib/ + tests/data/ back from the snapshot; revert code files outside them that were clean before."""
    meta = _load_json(SNAP / "snapshot.json", None)
    if meta is None:
        return False
    for d in meta["dirs"]:
        if (SNAP / d).exists():
            _sync_dir(SNAP / d, ROOT / d)
    before = set(meta.get("dirty", ()))
    for p in sorted(_git_dirty() - before):
        if any(p == d or p.startswith(d + "/") for d in meta["dirs"]):
            continue
        tracked = subprocess.run(["git", "ls-files", "--error-unmatch", p], cwd=ROOT, capture_output=True).returncode == 0
        if tracked:
            subprocess.run(["git", "checkout", "--", p], cwd=ROOT, capture_output=True)
        else:
            (ROOT / p).unlink(missing_ok=True)
    shutil.rmtree(SNAP, ignore_errors=True)
    log(f"[prebuild] restored lib/ + tests/data/ from the snapshot{f' ({reason})' if reason else ''}")
    return True


def recover(log=print):
    """A snapshot left on disk = a prebuild died mid-target (killed / host suspend): restore it."""
    if SNAP.exists():
        return restore(log, "interrupted prebuild")
    return False


# ------------------------------------------------------------------------------------------------ lock + stop
def _pid_alive(pid):
    try:
        os.kill(pid, 0)
        return True
    except (ProcessLookupError, PermissionError, ValueError, TypeError):
        return False


def lock_holder():
    try:
        pid = int(json.loads(LOCK.read_text()).get("pid"))
    except (OSError, ValueError, TypeError, AttributeError):
        return None
    return pid if _pid_alive(pid) else None


def _in_root(pid):
    """Is the process's working directory this copy's ROOT or beneath it? Path components, never a string prefix:
    ~/huntress-2026-rehearsal starts with ~/huntress-2026."""
    try:
        cwd = Path(os.readlink(f"/proc/{pid}/cwd")).resolve()
    except OSError:
        return False
    root = ROOT.resolve()
    return cwd == root or root in cwd.parents


def _worker_pids():
    """THIS copy's processes started with HCTF_PREBUILD=1 in their environment (the prebuild's claude worker +
    children). Host-wide matching let main's `prebuild --stop` kill the rehearsal copy's prebuild workers (D22 post-mortem)."""
    out = []
    for env in Path("/proc").glob("[0-9]*/environ"):
        try:
            if b"HCTF_PREBUILD=1\x00" in env.read_bytes():
                out.append(int(env.parent.name))
        except (OSError, ValueError):
            continue
    return [p for p in out if p != os.getpid() and _in_root(p)]


_PREBUILD_SEG = re.compile(r"\S*python[\d.]*\s+-m\s+hctf\.cli\s+prebuild\b(?![^;&|]*--(?:stop|list|recover)\b)")


def _shell_script(argv):
    """The script of a `bash|sh [-l] -c|-lc <script>` argv, else None."""
    if not argv or Path(argv[0]).name not in ("bash", "sh"):
        return None
    for i, a in enumerate(argv[1:], 1):
        if not a.startswith("-"):
            return None
        if "c" in a[1:] and i + 1 < len(argv):
            return argv[i + 1]
    return None


def stop(log=print, grace=15.0):
    """Stop a running prebuild NOW (bin/day.sh before a run): SIGTERM the batch (it kills its worker and restores the
    snapshot), SIGKILL whatever is left after `grace` s, then recover any leftover snapshot. Returns True if one ran."""
    pid = lock_holder()
    # every prebuild process, not just the lock holder: the post-run chain is `bash -c 'prebuild --lane A ; prebuild
    # --lane B ; ...'` -- killing only the current batch let the chain start the next lane, and a later --stop then
    # "recovered" (restored) the snapshot UNDER that live batch (2026-10-16: 3 mobile targets falsely reverted)
    shells, batches = _batch_pids()
    for sp in shells:                       # the chain first, so it cannot start another lane
        try:
            os.kill(sp, signal.SIGTERM)
        except (ProcessLookupError, PermissionError):
            pass
    ran = pid is not None or bool(_worker_pids()) or bool(shells or batches)
    for bp in batches:
        if bp != pid:
            try:
                os.kill(bp, signal.SIGTERM)
            except (ProcessLookupError, PermissionError):
                pass
    if pid:
        log(f"[prebuild] stopping batch pid {pid}")
        try:
            os.kill(pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
        end = time.time() + grace
        while time.time() < end and _pid_alive(pid):
            time.sleep(0.2)
        if _pid_alive(pid):
            try:
                os.kill(pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
    for wp in _worker_pids():
        try:
            os.kill(wp, signal.SIGKILL)
        except (ProcessLookupError, PermissionError):
            pass
    end = time.time() + grace
    while time.time() < end and any(_pid_alive(b) for b in batches):
        time.sleep(0.2)
    for bp in batches:
        if _pid_alive(bp):
            try:
                os.kill(bp, signal.SIGKILL)
            except (ProcessLookupError, PermissionError):
                pass
    LOCK.unlink(missing_ok=True)
    if any(_pid_alive(b) for b in _batch_pids()[1]):
        log("[prebuild] a prebuild batch is still alive: NOT recovering its snapshot (run --stop again)")
        return ran
    recover(log)
    return ran


def _batch_pids():
    """([chain shell pids], [batch pids]) of running prebuilds, matched STRICTLY (a substring match also hit an
    operator's / the assistant's own shell whose command text merely mentioned the CLI, and SIGTERMed it):
    batch = argv contains `-m hctf.cli prebuild` as separate args (not --stop/--list/--recover);
    chain shell = `bash|sh -c <script>` whose script STARTS with an interpreter running `-m hctf.cli prebuild`."""
    me = os.getpid()
    shells, batches = [], []
    for c in Path("/proc").glob("[0-9]*/cmdline"):
        try:
            pid = int(c.parent.name)
            argv = [a.decode(errors="replace") for a in c.read_bytes().split(b"\0") if a]
        except (OSError, ValueError):
            continue
        if pid == me or not argv:
            continue
        try:   # this copy's batches only (main and alt share the box)
            if Path(os.readlink(f"/proc/{pid}/cwd")).resolve() != ROOT.resolve():
                continue
        except OSError:
            continue
        if any(argv[i:i + 3] == ["-m", "hctf.cli", "prebuild"] for i in range(len(argv))):
            if not any(x in argv for x in ("--stop", "--list", "--recover")):
                batches.append(pid)
            continue
        # a chain shell: one of its `;` / `&&` / `||` segments STARTS with the prebuild CLI (also the post-run /
        # restart shape `bash -lc 'cd ROOT && source bin/env.sh; .venv/bin/python3 -m hctf.cli prebuild ...'`, which the
        # old argv[1] == "-c" + script-starts-with match missed -- D22 post-mortem); a mention (grep, --stop) never is
        script = _shell_script(argv)
        if script and any(_PREBUILD_SEG.match(seg.strip()) for seg in re.split(r"&&|\|\||;", script)):
            shells.append(pid)
    return shells, batches


