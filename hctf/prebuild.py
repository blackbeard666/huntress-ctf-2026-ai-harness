def _in(path, prefixes):
    """`path` is one of `prefixes` or lies under one (a trailing '/' marks a directory)."""
    return any(path == p.rstrip("/") or path.startswith(p.rstrip("/") + "/") for p in prefixes)


def check_meta_fixtures(root=None):
    """Every tests/data/meta_fixtures/<fmt>/<case>.{bin,json} through lib.meta.answer -> [problem strings].
    Fixture json: {field: "fmt.field", expected, generator_cmd, oracle_cmd[, decoy, member, answer_format]}."""
    root = Path(root or ROOT)
    sys.path.insert(0, str(root))
    from lib import meta
    probs = []
    for fj in sorted((root / "tests" / "data" / "meta_fixtures").glob("*/*.json")):
        try:
            fx = json.loads(fj.read_text())
        except ValueError as e:
            probs.append(f"{fj.name}: bad json {e}")
            continue
        fmt_field = str(fx.get("field") or "")
        fmt, _, field = fmt_field.partition(".")
        binf = fj.with_suffix(".bin")
        if not (fmt and field and binf.exists() and "expected" in fx):
            probs.append(f"{fj.relative_to(root)}: needs field 'fmt.field', expected, and a sibling .bin")
            continue
        name = fx.get("member") or binf.name
        aid = f"d00-{fmt}-001-{fmt}-{field.replace('_', '-')}"
        q = {"id": aid, "question": f"Determine {fmt}.{field} for {name}.", "artifact": f"fixture.zip -> {name}",
             "answer_format": fx.get("answer_format") or {}, "normalization": "trim"}
        t0 = time.time()
        try:
            got, _tier = meta.answer(aid, q, binf.read_bytes())
        except Exception as e:  # noqa: BLE001
            probs.append(f"{fj.relative_to(root)}: extractor raised {e!r}")
            continue
        budget = 1.0 * float(os.environ.get("HCTF_TEST_TIME_SLACK", "1"))   # 2x inside a loaded parallel gate
        if time.time() - t0 > budget:
            probs.append(f"{fj.relative_to(root)}: {time.time() - t0:.2f}s (> {budget:g} s in-window budget)")
        if str(got) != str(fx["expected"]):
            probs.append(f"{fj.relative_to(root)}: {fmt_field} got {got!r}, expected {fx['expected']!r}")
    return probs


