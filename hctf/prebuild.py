def _target_done(lane, t, reg):
    if lane == "metadata-forensics" and t.get("fmt") and t.get("fields"):
        return all((t["fmt"], f) in reg for f in t["fields"])
    return False


def pending(lane, cfg, n, only=None):
    """The next `n` targets: ranked order, minus done ones and ones that failed MAX_ATTEMPTS times."""
    state = _load_json(STATE, {})
    reg = registered_fields() if lane == "metadata-forensics" else set()
    out = []
    for t in targets(cfg):
        tid = t.get("id")
        if not tid or (only and tid not in only):
            continue
        st = state.get(f"{lane}:{tid}", {})
        if st.get("ok") or _target_done(lane, t, reg) or (not only and st.get("attempts", 0) >= MAX_ATTEMPTS):
            continue
        out.append(t)
    for tid in only or ():
        if not any(t.get("id") == tid for t in out) and not any(t.get("id") == tid for t in targets(cfg)):
            out.append({"id": tid, "goal": tid})       # ad-hoc target named on the command line
    return out[:n] if n else out


def _record(lane, tid, **kw):
    state = _load_json(STATE, {})
    st = state.setdefault(f"{lane}:{tid}", {"attempts": 0})
    st["attempts"] = st.get("attempts", 0) + 1
    st.update(kw, last=time.strftime("%Y-%m-%dT%H:%M:%S"))
    STATE.write_text(json.dumps(state, indent=1, sort_keys=True))


