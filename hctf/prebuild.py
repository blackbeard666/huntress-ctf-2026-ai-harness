def _requires_met(cfg):
    for req in cfg.get("requires", ()):
        path, _, sym = req.partition(":")
        p = ROOT / path
        if not p.exists():
            return False
        if sym and not re.search(rf"^(?:def\s+{re.escape(sym)}\b|{re.escape(sym)}\s*=)", p.read_text(errors="replace"),
                                 re.M):
            return False
    return True


