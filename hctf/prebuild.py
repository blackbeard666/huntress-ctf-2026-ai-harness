def meta_structure_problems(root=None):
    """Prebuilt modules: registry conflicts, FIELDS funcs defined, >= 2 fixtures incl. a decoy per module, provenance."""
    root = Path(root or ROOT)
    r = subprocess.run([sys.executable, "-c", "import json, lib.meta as m; print(json.dumps([list(map(str, c)) "
                        "for c in m.CONFLICTS]))"], cwd=root, capture_output=True, text=True, timeout=60,
                       env=dict(os.environ, PYTHONPATH=str(root)))
    probs = []
    try:
        conf = json.loads(r.stdout.strip().splitlines()[-1])
    except (IndexError, ValueError):
        return [f"lib.meta does not import: {r.stderr.strip()[-400:]}"]
    probs += [f"registry conflict: {c}" for c in conf]
    fixdir = root / "tests" / "data" / "meta_fixtures"
    for mod in sorted((root / "lib" / "meta" / "prebuilt").glob("*.py")):
        if mod.name.startswith("_"):
            continue
        src = mod.read_text()
        tree = ast.parse(src)
        funcs = {n.name for n in tree.body if isinstance(n, ast.FunctionDef)}
        from lib.meta import _prebuilt_fields
        fields = _prebuilt_fields(mod)
        if not fields:
            probs.append(f"{mod.name}: no literal FIELDS dict")
        fmts = set()
        for key, fn in fields.items():
            if fn not in funcs:
                probs.append(f"{mod.name}: FIELDS {key} -> {fn}() is not defined at module level")
            if isinstance(key, tuple) and key:
                fmts.add(key[0])
        for fmt in fmts:
            fx = [_load_json(p, {}) for p in sorted((fixdir / fmt).glob("*.json"))]
            mine = [f for f in fx if str(f.get("field", "")).split(".")[0] == fmt]
            if len(mine) < 2:
                probs.append(f"{mod.name}: {fmt} needs >= 2 fixtures in tests/data/meta_fixtures/{fmt}/ (has {len(mine)})")
            if not any(f.get("decoy") or str(f.get("expected")) == "none" for f in mine):
                probs.append(f"{mod.name}: {fmt} fixtures need a decoy (decoy: true / expected \"none\")")
            for f in mine:
                if not (f.get("generator_cmd") and f.get("oracle_cmd")):
                    probs.append(f"{mod.name}: fixture {f.get('field')} lacks generator_cmd / oracle_cmd provenance")
                elif re.search(r"lib[./]meta", str(f.get("oracle_cmd"))):
                    probs.append(f"{mod.name}: fixture oracle must be an independent standard reader, not lib.meta")
    return probs


def regress_baseline(lane):
    """{(solver, case): ok} for every verified case of every day of `lane` (warmups/binary gate)."""
    from . import solvers
    out = {}
    for sdir in paths.all_solver_dirs():
        if solvers._lane_of(sdir) != lane:
            continue
        for r in solvers.test_solver(sdir):
            if not r.get("unverified") and not r["case"].startswith("synthetic-"):
                out[(str(sdir.relative_to(ROOT)), r["case"])] = bool(r["ok"])
    return out


def gate(lane, cfg, snap_root, before_dirty, before_src, base_regress=None, log=print):
    """(ok, [reasons]). Never raises."""
    reasons = []
    try:
        changed = changed_paths(snap_root, cfg)
        if not changed:
            return False, ["no change (nothing written)"]
        outside = [p for p in changed if not _in(p, cfg["writable"])]
        outside += sorted(p for p in _git_dirty() - before_dirty
                          if not _in(p, cfg["writable"]) and not _in(p, cfg["snapshot"]))
        if outside:
            reasons.append("wrote outside the allowlist: " + ", ".join(outside[:8]))
        for p in changed:
            if p.endswith(".py") and (ROOT / p).exists():
                reasons += ast_problems(ROOT / p, before_src.get(p))
        if "meta" in cfg.get("checks", ()):
            reasons += meta_structure_problems() + _fresh_fixture_problems()
        if reasons:
            return False, reasons
        from . import orchestrate
        for t in dict.fromkeys(tuple(cfg.get("gate", ())) + tuple(orchestrate.RATCHET_GATE)):
            if not (ROOT / t).exists():
                continue
            try:
                rc = subprocess.run([sys.executable, t], cwd=ROOT, capture_output=True, text=True, timeout=900,
                                    env=dict(os.environ, HCTF_META_MAX_DAY="0"))
                if rc.returncode:
                    tail = (rc.stdout + rc.stderr).strip().splitlines()[-3:]
                    reasons.append(f"{t} fails: {' | '.join(tail)[:400]}")
            except subprocess.TimeoutExpired:
                reasons.append(f"{t} timed out")
        if cfg.get("regress_lane") and base_regress is not None:
            after = regress_baseline(cfg["regress_lane"])
            broke = [k for k, ok in base_regress.items() if ok and not after.get(k)]
            if broke:
                reasons.append(f"{len(broke)} verified {cfg['regress_lane']} case(s) regress: {broke[:4]}")
    except Exception as e:  # noqa: BLE001 - a crashing gate is a failing gate
        reasons.append(f"gate error {e!r}")
    return not reasons, reasons


# ------------------------------------------------------------------------------------------------ snapshot
def snapshot(cfg):
    shutil.rmtree(SNAP, ignore_errors=True)
    SNAP.mkdir(parents=True)
    for d in cfg["snapshot"]:
        if (ROOT / d).exists():
            shutil.copytree(ROOT / d, SNAP / d, ignore=shutil.ignore_patterns("__pycache__"))
    (SNAP / "snapshot.json").write_text(json.dumps({"dirs": list(cfg["snapshot"]), "dirty": sorted(_git_dirty()),
                                                    "t": time.time()}))
    return SNAP


def restore(log=print, reason=""):
    """Put lib/ + tests/data/ back from the snapshot; revert code files outside them that were clean before."""
    meta = _load_json(SNAP / "snapshot.json", None)
    if meta is None:
        return False
    for d in meta["dirs"]:
        if (SNAP / d).exists():
            shutil.rmtree(ROOT / d, ignore_errors=True)
            shutil.copytree(SNAP / d, ROOT / d)
    before = set(meta.get("dirty", ()))
    for p in sorted(_git_dirty() - before):
        if any(p == d or p.startswith(d + "/") for d in meta["dirs"]):
            continue
        tracked = subprocess.run(["git", "ls-files", "--error-unmatch", p], cwd=ROOT, capture_output=True).returncode == 0
        if tracked:
            subprocess.run(["git", "checkout", "--", p], cwd=ROOT, capture_output=True)
        else:
            (ROOT / p).unlink(missing_ok=True)
    shutil.rmtree(SNAP, ignore_errors=True)
    log(f"[prebuild] restored lib/ + tests/data/ from the snapshot{f' ({reason})' if reason else ''}")
    return True


def recover(log=print):
    """A snapshot left on disk = a prebuild died mid-target (killed / host suspend): restore it."""
    if SNAP.exists():
        return restore(log, "interrupted prebuild")
    return False


# ------------------------------------------------------------------------------------------------ lock + stop
def _pid_alive(pid):
    try:
        os.kill(pid, 0)
        return True
    except (ProcessLookupError, PermissionError, ValueError, TypeError):
        return False


def lock_holder():
    try:
        pid = int(json.loads(LOCK.read_text()).get("pid"))
    except (OSError, ValueError, TypeError, AttributeError):
        return None
    return pid if _pid_alive(pid) else None


def _worker_pids():
    """Processes started with HCTF_PREBUILD=1 in their environment (the prebuild's claude worker + children)."""
    out = []
    for env in Path("/proc").glob("[0-9]*/environ"):
        try:
            if b"HCTF_PREBUILD=1\x00" in env.read_bytes():
                out.append(int(env.parent.name))
        except (OSError, ValueError):
            continue
    return [p for p in out if p != os.getpid()]


def stop(log=print, grace=15.0):
    """Stop a running prebuild NOW (bin/day.sh before a run): SIGTERM the batch (it kills its worker and restores the
    snapshot), SIGKILL whatever is left after `grace` s, then recover any leftover snapshot. Returns True if one ran."""
    pid = lock_holder()
    ran = pid is not None or bool(_worker_pids())
    if pid:
        log(f"[prebuild] stopping batch pid {pid}")
        try:
            os.kill(pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
        end = time.time() + grace
        while time.time() < end and _pid_alive(pid):
            time.sleep(0.2)
        if _pid_alive(pid):
            try:
                os.kill(pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
    for wp in _worker_pids():
        try:
            os.kill(wp, signal.SIGKILL)
        except (ProcessLookupError, PermissionError):
            pass
    LOCK.unlink(missing_ok=True)
    recover(log)
    return ran


# ------------------------------------------------------------------------------------------------ the batch
def _render(lane, cfg, t, budget_left, deadline):
    brief = ""
    bp = workers.PROMPTS / f"{cfg['brief']}.md"
    if bp.exists():
        brief = bp.read_text()
        if lane == "metadata-forensics":
            try:
                from lib import meta
                reg = "\n".join(f"  - {f}.{fld}: {e.tier}" + (f" (GM-verified D{min(e.days)})" if e.days else "")
                                for (f, fld), e in sorted(meta.REGISTRY.items()))
            except Exception as e:  # noqa: BLE001
                reg = f"(registry unavailable: {e})"
            brief = brief.replace("{registry}", reg).replace(
                "{example}", (ROOT / "lib" / "meta" / "msi.py").read_text())
    return workers.render("prebuild", lane=lane, target_id=t.get("id", "?"),
                          target=json.dumps(t, indent=2, ensure_ascii=False), brief=brief,
                          writable="\n".join(f"- `{w}`" for w in cfg["writable"]),
                          gate="\n".join(f"- `python3 {g}`" for g in cfg.get("gate", ())) or "- (lane regression only)",
                          deadline=deadline.strftime("%H:%M"), minutes=int(TIMEOUT // 60))


def run(lane, n=None, only=None, budget_usd=None, deadline=None, log=print, runner=None):
    """Run up to `n` prebuild workers for `lane`, one target at a time, each gated + transactional.
    `runner(chal_dir, stage, prompt, env, timeout, stop)` defaults to workers.run_local (tests pass a stub).
    Returns [{target, ok, reasons, cost, rc, log}]."""
    lane = lane_key(lane)
    cfg = LANES.get(lane)
    if cfg is None:
        log(f"[prebuild] unknown lane {lane!r} (known: {', '.join(LANES)})")
        return []
    if not _requires_met(cfg):
        log(f"[prebuild] {lane}: not available yet (needs {', '.join(cfg['requires'])})")
        return []
    holder = lock_holder()
    if holder and holder != os.getpid():
        log(f"[prebuild] another prebuild is running (pid {holder}); not starting a second one")
        return []
    RUN.mkdir(parents=True, exist_ok=True)
    LOCK.write_text(json.dumps({"pid": os.getpid(), "lane": lane, "t": time.time()}))
    recover(log)
    n = n or DEFAULT_N
    budget = budget_usd if budget_usd is not None else budget_for(n)
    deadline = deadline or default_deadline()
    runner = runner or workers.run_local
    stop_evt = threading.Event()
    prev = {}

    def on_term(signum, frame):
        stop_evt.set()
    if threading.current_thread() is threading.main_thread():
        for s in (signal.SIGTERM, signal.SIGINT):
            prev[s] = signal.signal(s, on_term)
    results, spent = [], 0.0
    try:
        todo = pending(lane, cfg, n, only)
        log(f"[prebuild] {lane}: {len(todo)} target(s) {[t.get('id') for t in todo]}, budget ${budget:.2f}, "
            f"deadline {deadline:%Y-%m-%d %H:%M}")
        hist = history_costs()
        for t in todo:
            est = statistics.median(hist) if hist else DEFAULT_COST
            left = (deadline - datetime.now()).total_seconds()
            if stop_evt.is_set():
                log("[prebuild] stopped")
                break
            if spent + est > budget:
                log(f"[prebuild] budget: ${spent:.2f} spent + ~${est:.2f} next > ${budget:.2f}; stopping")
                break
            if left < 120:
                log(f"[prebuild] deadline {deadline:%H:%M} reached; stopping")
                break
            tid = t.get("id")
            snap = snapshot(cfg)
            meta = _load_json(snap / "snapshot.json", {})
            before_dirty = set(meta.get("dirty", ()))
            before_src = {}
            for d in cfg["snapshot"]:
                for p in (snap / d).rglob("*.py") if (snap / d).exists() else ():
                    before_src[str(p.relative_to(snap))] = p.read_text(errors="replace")
            base_regress = regress_baseline(cfg["regress_lane"]) if cfg.get("regress_lane") else None
            prompt = _render(lane, cfg, t, budget - spent, deadline)
            env = {"HCTF_STAGE": "prebuild", "HCTF_LANE": lane, "HCTF_PREBUILD": "1", "HCTF_BASE": f"prebuild-{lane}",
                   "HCTF_CHAL": f"prebuild:{tid}"}
            LOGDIR.mkdir(parents=True, exist_ok=True)
            t0 = time.time()
            log(f"[prebuild] {lane}/{tid}: worker start (timeout {min(TIMEOUT, left - 60):.0f}s)")
            rc, wlog = runner(LOGDIR / lane, "prebuild", prompt, env, min(TIMEOUT, left - 60), stop_evt)
            cost = 0.0
            try:
                cost = float(workers.worker_outcome(wlog).get("cost_usd") or 0.0)
            except Exception:  # noqa: BLE001
                pass
            spent += cost
            if cost:
                hist.append(cost)
            if stop_evt.is_set():
                restore(log, "stopped mid-target")
                results.append({"target": tid, "ok": False, "reasons": ["stopped"], "cost": cost, "rc": rc, "log": str(wlog)})
                break
            ok, reasons = gate(lane, cfg, snap, before_dirty, before_src, base_regress, log)
            if ok:
                shutil.rmtree(SNAP, ignore_errors=True)
                log(f"[prebuild] {lane}/{tid}: KEPT (gate green, {time.time() - t0:.0f}s, ${cost:.2f})")
            else:
                restore(log, f"gate failed for {tid}")
                log(f"[prebuild] {lane}/{tid}: REVERTED ({'; '.join(reasons)[:600]})")
            _record(lane, tid, ok=ok, reasons=reasons[:6], cost=cost, rc=rc, log=str(wlog))
            results.append({"target": tid, "ok": ok, "reasons": reasons, "cost": cost, "rc": rc, "log": str(wlog)})
        log(f"[prebuild] {lane}: {sum(r['ok'] for r in results)}/{len(results)} kept, ${spent:.2f} spent")
        return results
    finally:
        recover(log)
        for s, h in prev.items():
            signal.signal(s, h)
        try:
            if json.loads(LOCK.read_text()).get("pid") == os.getpid():
                LOCK.unlink()
        except (OSError, ValueError):
            pass


