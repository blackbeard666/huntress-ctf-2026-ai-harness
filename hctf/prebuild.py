def launch_background(day=None, log=print, popen=subprocess.Popen):
    """After ratchet + speed_harden: one DETACHED `hctf prebuild` per enabled lane, chained in one shell, with a budget
    from the metrics history and a deadline DEADLINE_MARGIN_MIN before the next drop. Returns the Popen or None."""
    lanes = [lane_key(x) for x in AUTO_LANES if lane_key(x) in enabled_lanes()]
    if not lanes:
        log("[prebuild] no lane available for the post-run prebuild")
        return None
    if lock_holder():
        log("[prebuild] a prebuild is already running; not launching another")
        return None
    dl = default_deadline()
    if (dl - datetime.now()).total_seconds() < 15 * 60:
        log(f"[prebuild] skipped: under 15 min to the {dl:%H:%M} prebuild deadline")
        return None
    n = DEFAULT_N
    budget = budget_for(n)
    tag = f"day{int(day):02d}" if day else time.strftime("%Y%m%d")
    out = RUN / f"prebuild-{tag}.log"
    cmds = [f"{sys.executable} -m hctf.cli prebuild --lane {ln} --n {n} --budget-usd {budget} --deadline {dl:%H:%M}"
            for ln in lanes]
    p = popen(["bash", "-c", " ; ".join(cmds)], cwd=ROOT, stdout=open(out, "a"), stderr=subprocess.STDOUT,
              start_new_session=True, env=dict(os.environ, PYTHONPATH=str(ROOT)))
    log(f"[prebuild] launched in the background for {', '.join(lanes)} (n={n}/lane, ${budget}/lane, deadline "
        f"{dl:%H:%M}) -> {out.relative_to(ROOT)}; `hctf prebuild --stop` ends it")
    return p
