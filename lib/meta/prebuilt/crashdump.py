def _u(b, off, fmt):
    try:
        return struct.unpack_from("<" + fmt, b, off)[0]
    except struct.error:
        return None


def _unix(v):
    if v is None:
        return None
    try:
        return datetime.datetime.fromtimestamp(v, datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    except (OverflowError, OSError, ValueError):
        return None


def _filetime(v):
    if v is None or v in (0, _FILL64):
        return NONE
    try:
        dt = datetime.datetime(1601, 1, 1, tzinfo=datetime.timezone.utc) + datetime.timedelta(microseconds=v // 10)
    except OverflowError:
        return None
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


