def _kd_value(b, field, param=None):
    is64 = b[4:8] == b"DU64"
    if len(b) < (0x1040 if is64 else 0xfc8):
        return None
    w = 16 if is64 else 8
    q = "Q" if is64 else "I"
    lay = ({"dtb": 0x10, "psl": 0x20, "mach": 0x30, "nproc": 0x34, "bug": 0x38, "par": 0x40, "kdbg": 0x80,
            "dtype": 0xf98, "stime": 0xfa8, "comment": 0xfb0} if is64 else
           {"dtb": 0x10, "psl": 0x18, "mach": 0x20, "nproc": 0x24, "bug": 0x28, "par": 0x2c, "kdbg": 0x60,
            "dtype": 0xf88, "stime": 0xfc0, "comment": 0x820})
    maj, mnr = struct.unpack_from("<II", b, 8)
    if field == "bugcheck_parameter":
        try:
            i = int((param or "").lstrip("_")[:1]) - 1
        except ValueError:
            return None
        if not 0 <= i < 4:
            return None
        return Hex(_u(b, lay["par"] + i * (w // 2), q), w)
    if field == "comment":
        raw = b[lay["comment"]:lay["comment"] + 128].split(b"\x00", 1)[0]
        txt = raw.decode("latin-1").strip()
        return txt if txt.replace("PAGE", "").strip() else NONE
    dtype = _u(b, lay["dtype"], "I")
    v = {"signature": b[:8].decode("latin-1"), "bitness": 64 if is64 else 32, "is_64bit": is64,
         "major_version": maj, "minor_version": mnr, "build_number": mnr, "version": f"{maj}.{mnr}",
         "machine_image_type_u32_hex": Hex(_u(b, lay["mach"], "I"), 8),
         "number_processors": _u(b, lay["nproc"], "I"),
         "bugcheck_code_u32_hex": Hex(_u(b, lay["bug"], "I"), 8),
         "bugcheck_parameters": ["0x%0*x" % (w, _u(b, lay["par"] + i * (w // 2), q)) for i in range(4)],
         "directory_table_base_hex": Hex(_u(b, lay["dtb"], q), w),
         "ps_loaded_module_list_hex": Hex(_u(b, lay["psl"], q), w),
         "kd_debugger_data_block_hex": Hex(_u(b, lay["kdbg"], q), w),
         "dump_type": dtype, "dump_type_name": _DUMP_TYPES.get(dtype, str(dtype)),
         "system_time": _filetime(_u(b, lay["stime"], "Q"))}
    if field == "pae_enabled":
        return NONE if is64 else bool(b[0x5c])
    val = v.get(field)
    if isinstance(val, Hex) and val.value in (_FILL32, _FILL64):
        return NONE
    if isinstance(val, int) and not isinstance(val, bool) and val == _FILL32:
        return NONE
    return val


