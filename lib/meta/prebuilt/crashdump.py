def _md_string(b, rva):
    n = _u(b, rva, "I")
    if n is None or n > 0x10000 or rva + 4 + n > len(b):
        return None
    return b[rva + 4:rva + 4 + n].decode("utf-16-le", "replace").rstrip("\x00")


def _md_streams(b):
    """[(type, size, rva)] of the stream directory, or None (truncated)."""
    n, rva = _u(b, 8, "I"), _u(b, 12, "I")
    if n is None or rva is None or n > 4096 or rva + 12 * n > len(b):
        return None
    return [struct.unpack_from("<III", b, rva + 12 * i) for i in range(n)]


def _md_stream(b, dirs, typ):
    """(rva, size) of the first `typ` stream; None when the dump has none; ValueError (-> None) when it is cut off."""
    for t, size, rva in dirs:
        if t == typ:
            if rva + size > len(b):
                raise ValueError("stream past EOF")
            return rva, size
    return None


def _md_value(b, field):
    if len(b) < 32:
        return None
    ver, impl, nstreams, dir_rva, csum, ts = struct.unpack_from("<HHIIII", b, 4)
    flags = _u(b, 24, "Q")
    head = {"signature": "MDMP", "version": Hex(ver, 4), "version_u16_hex": Hex(ver, 4),
            "implementation_version": impl, "implementation_version_u16_hex": Hex(impl, 4),
            "version_u32_hex": Hex(ver | impl << 16, 8), "number_of_streams": nstreams,
            "stream_directory_rva": dir_rva, "stream_directory_rva_hex": Hex(dir_rva, 8), "checksum_u32_hex": Hex(csum, 8),
            "time_date_stamp": _unix(ts), "time_date_stamp_unix": ts, "time_date_stamp_u32_hex": Hex(ts, 8),
            "flags_u64_hex": Hex(flags, 16)}
    if field in head:
        return head[field]
    dirs = _md_streams(b)
    if dirs is None:
        return None
    types = [t for t, _s, _r in dirs]
    if field == "stream_types":
        return types
    if field == "stream_type_names":
        return [_STREAM_NAMES.get(t, str(t)) for t in types]
    if field == "has_exception_stream":
        return 6 in types
    if field in ("processor_architecture", "processor_architecture_u16_hex", "processor_architecture_name",
                 "processor_level", "processor_revision", "number_of_processors", "product_type", "major_version",
                 "minor_version", "build_number", "os_version", "platform_id", "csd_version", "suite_mask_u16_hex"):
        s = _md_stream(b, dirs, 7)
        if s is None:
            return NONE
        o = s[0]
        if o + 32 > len(b):
            return None
        arch, lvl, rev, nproc, ptype, maj, mnr, bld, plat, csd_rva, suite = struct.unpack_from("<HHHBBIIIIIH", b, o)
        if field == "csd_version":
            v = _md_string(b, csd_rva)
            return v if v else NONE   # an empty CSD string (no service pack) has nothing to spell
        return {"processor_architecture": _ARCH.get(arch, str(arch)), "processor_architecture_name": _ARCH.get(arch, str(arch)),
                "processor_architecture_u16_hex": Hex(arch, 4), "processor_level": lvl, "processor_revision": rev,
                "number_of_processors": nproc, "product_type": ptype, "major_version": maj, "minor_version": mnr,
                "build_number": bld, "os_version": f"{maj}.{mnr}.{bld}", "platform_id": plat,
                "suite_mask_u16_hex": Hex(suite, 4)}[field]
    if field.startswith(("module", "main_module")):
        s = _md_stream(b, dirs, 4)
        if s is None:
            return NONE
        n = _u(b, s[0], "I")
        if n is None or s[0] + 4 + 108 * n > len(b):
            return None
        mods = []
        for i in range(n):
            o = s[0] + 4 + 108 * i
            base, size, csum_m, ts_m, name_rva = struct.unpack_from("<QIIII", b, o)
            mods.append((base, size, csum_m, ts_m, _md_string(b, name_rva)))
        if field == "module_count":
            return n
        if field == "module_names":
            return [m[4] for m in mods]
        if field == "module_basenames":
            return [(m[4] or "").replace("/", "\\").rsplit("\\", 1)[-1] for m in mods]
        if field == "module_base_addresses":
            return ["0x%016x" % m[0] for m in mods]
        if not mods:
            return NONE
        m = mods[0]
        return {"main_module": m[4], "main_module_basename": (m[4] or "").replace("/", "\\").rsplit("\\", 1)[-1],
                "main_module_base_u64_hex": Hex(m[0], 16), "main_module_size_of_image": m[1],
                "main_module_checksum_u32_hex": Hex(m[2], 8), "main_module_time_date_stamp_u32_hex": Hex(m[3], 8),
                "main_module_time_date_stamp": _unix(m[3])}.get(field)
    if field.startswith("exception"):
        s = _md_stream(b, dirs, 6)
        if s is None:
            return NONE
        o = s[0]
        if o + 40 > len(b):
            return None
        tid = _u(b, o, "I")
        code, eflags, _rec, addr, nparam = struct.unpack_from("<IIQQI", b, o + 8)
        return {"exception_code_u32_hex": Hex(code, 8), "exception_flags_u32_hex": Hex(eflags, 8),
                "exception_address_u64_hex": Hex(addr, 16), "exception_thread_id": tid,
                "exception_number_parameters": nparam}.get(field)
    if field in ("thread_count", "thread_ids"):
        s = _md_stream(b, dirs, 3)
        if s is None:
            return NONE
        n = _u(b, s[0], "I")
        if n is None or s[0] + 4 + 48 * n > len(b):
            return None
        return n if field == "thread_count" else [_u(b, s[0] + 4 + 48 * i, "I") for i in range(n)]
    if field in ("process_id", "process_create_time"):
        s = _md_stream(b, dirs, 15)
        if s is None or s[1] < 16:
            return NONE
        f1, pid, ctime = struct.unpack_from("<III", b, s[0] + 4)
        if field == "process_id":
            return pid if f1 & 1 else NONE
        return _unix(ctime) if f1 & 2 else NONE
    if field == "memory_range_count":
        s = _md_stream(b, dirs, 9)
        if s is not None:
            return _u(b, s[0], "Q")
        s = _md_stream(b, dirs, 5)
        return _u(b, s[0], "I") if s else NONE
    if field == "handle_count":
        s = _md_stream(b, dirs, 12)
        return _u(b, s[0] + 8, "I") if s and s[1] >= 16 else NONE
    return None


