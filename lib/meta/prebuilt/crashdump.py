def dump_value(data, ctx):
    """<fmt>.<field> of a minidump / kernel dump; the magic picks the parser, the format word what may be asked."""
    if data is None:
        return None
    fmt, field, param = ctx.get("fmt") or "", ctx.get("field") or "", ctx.get("param")
    b = bytes(data)
    try:
        if b[:4] == b"MDMP" and fmt not in _KD_FMTS:
            if _MD_ALIAS.get(field, field) not in _MD_KEYS:
                return NONE
            return _md_value(b, _MD_ALIAS.get(field, field))
        if b[:8] in (b"PAGEDU64", b"PAGEDUMP") and fmt not in _MD_FMTS:
            f = _kd_field(field)
            if f not in _KD_KEYS:
                return NONE
            if f == "bugcheck_parameter":
                param = _PARAM.match(field).group(1)
            return _kd_value(b, f, param)
        return NONE
    except (struct.error, IndexError, ValueError, KeyError):
        return None


def hiberfil_value(data, ctx):
    """hiberfil.<field>: the PO_MEMORY_IMAGE signature word @0 and the state it means."""
    if data is None:
        return None
    b = bytes(data)
    if len(b) < 4096 or b[:4] not in _HIB:   # hiberfil.sys is page-granular; a short / foreign file is not one
        return NONE
    return _hib_value(b, _HB_ALIAS.get(ctx.get("field") or "", ctx.get("field") or ""))


